/** Event categories that feed the policy risk index. */
const POLICY_EVENT_CATEGORIES = new Set([
  "EXPORT_BAN",
  "EXPORT_RESTRICTION",
  "SANCTIONS",
  "GOVERNMENT_POLICY",
  "IMPORT_POLICY",
  "EXPORT_POLICY",
]);

/**
 * Derived index formulas. Each returns one point per calendar date so the
 * indices can be charted and used by the score engine at any historical date.
 */
function computeSulphurDerived(ctx: DerivedContext): DerivedSeries[] {
  const landed: DerivedPoint[] = [];
  const globalIndexRaw: DerivedPoint[] = [];
  const tightness: DerivedPoint[] = [];
  const demand: DerivedPoint[] = [];
  const freight: DerivedPoint[] = [];
  const policy: DerivedPoint[] = [];

  const parity = SULPHUR_CONFIG.importParity;
  if (!parity) return [];

  for (const date of ctx.calendar) {
    const fob = ctx.asOf("FOB_MIDDLE_EAST", date);
    const routeFreight = ctx.asOf("ME_CHINA_FREIGHT", date);
    const fx = ctx.asOf("USD_CNY", date);

    if (fob !== null && routeFreight !== null && fx !== null) {
      const cifUsd = (fob + routeFreight) * (1 + parity.insuranceRatePct / 100);
      const dutiedUsd = cifUsd * (1 + parity.dutyRatePct / 100);
      const baseCny = dutiedUsd * fx;
      const value =
        baseCny * (1 + parity.vatRatePct / 100) +
        baseCny * (parity.financingRatePct / 100) +
        parity.portCostsPerTonne +
        parity.otherCostsPerTonne;
      landed.push({ timestamp: date, value: Number(value.toFixed(0)) });
    }

    const cfr = ctx.asOf("CFR_CHINA", date);
    const vancouver = ctx.asOf("FOB_VANCOUVER", date);
    if (cfr !== null && fob !== null && vancouver !== null) {
      globalIndexRaw.push({
        timestamp: date,
        value: cfr * 0.5 + fob * 0.3 + vancouver * 0.2,
      });
    }

    const inventory = ctx.asOf("CHINA_PORT_INVENTORY", date);
    const arrivals = ctx.asOf("ESTIMATED_ARRIVALS", date);
    if (inventory !== null) {
      const stockScore = scaleTo100(inventory, 200, 70);
      const arrivalScore =
        arrivals === null ? stockScore : scaleTo100(arrivals, 35, 15);
      tightness.push({
        timestamp: date,
        value: Number((stockScore * 0.8 + arrivalScore * 0.2).toFixed(1)),
      });
    }

    const map = ctx.asOf("MAP_UTILIZATION", date);
    const dap = ctx.asOf("DAP_UTILIZATION", date);
    const acid = ctx.asOf("H2SO4_UTILIZATION", date);
    if (map !== null && dap !== null) {
      const acidScore =
        acid === null ? 50 : scaleTo100(acid, 58, 80);
      demand.push({
        timestamp: date,
        value: Number(
          (
            scaleTo100(map, 45, 72) * 0.45 +
            scaleTo100(dap, 40, 68) * 0.35 +
            acidScore * 0.2
          ).toFixed(1),
        ),
      });
    }

    if (routeFreight !== null) {
      freight.push({
        timestamp: date,
        value: Number(scaleTo100(routeFreight, 16, 36).toFixed(1)),
      });
    }

    // Policy risk decays with a 60-day event window; confidence weights impact.
    const recent = ctx
      .eventsBefore(date, 60)
      .filter((event) => POLICY_EVENT_CATEGORIES.has(event.category));
    const pressure = recent.reduce(
      (sum, event) => sum + Math.abs(event.impactScore) * (event.confidence / 100),
      0,
    );
    policy.push({
      timestamp: date,
      value: Number(Math.min(100, 30 + pressure * 3.5).toFixed(1)),
    });
  }

  const rebase = (points: DerivedPoint[]): DerivedPoint[] => {
    const base = points[0]?.value || 1;
    return points.map((p) => ({
      timestamp: p.timestamp,
      value: Number(((p.value / base) * 100).toFixed(1)),
    }));
  };

  return [
    { code: "CHINA_LANDED_COST", points: landed },
    { code: "CHINA_IMPORT_COST_INDEX", points: rebase(landed) },
    { code: "GLOBAL_SULPHUR_INDEX", points: rebase(globalIndexRaw) },
    { code: "CHINA_SUPPLY_TIGHTNESS_INDEX", points: tightness },
    { code: "DEMAND_STRENGTH_INDEX", points: demand },
    { code: "FREIGHT_PRESSURE_INDEX", points: freight },
    { code: "POLICY_RISK_INDEX", points: policy },
  ];
}

